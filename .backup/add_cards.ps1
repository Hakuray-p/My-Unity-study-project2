function ConvertTo-YamlEscaped([string]$s)
{
    $sb = New-Object System.Text.StringBuilder
    foreach ($ch in $s.ToCharArray())
    {
        $code = [int]$ch
        if ($ch -eq '"') { [void]$sb.Append('\"') }
        elseif ($ch -eq '\') { [void]$sb.Append('\\') }
        elseif ($code -lt 128) { [void]$sb.Append($ch) }
        else { [void]$sb.Append('\u' + $code.ToString('X4')) }
    }
    return $sb.ToString()
}

function ConvertTo-HexArray([string]$csv)
{
    if ([string]::IsNullOrEmpty($csv)) { return '[]' }
    $sb = New-Object System.Text.StringBuilder
    foreach ($p in $csv.Split(','))
    {
        foreach ($b in [System.BitConverter]::GetBytes([int]$p)) { [void]$sb.Append($b.ToString('X2')) }
    }
    return $sb.ToString().ToLower()
}

